import { GoogleGenerativeAI } from "@google/generative-ai";

const apiKey = process.env.GEMINI_API_KEY || "";
const genAI = apiKey ? new GoogleGenerativeAI(apiKey) : null;

export async function analyzeTranscriptChunk(
  transcript: string,
  existingBlueprint: object | null
): Promise<any> {
  if (!genAI) {
    console.warn("GEMINI_API_KEY is missing. Returning default structured preview.");
    return getDefaultAnalysis(transcript);
  }

  const model = genAI.getGenerativeModel({ 
    model: "gemini-2.5-flash",
    generationConfig: { responseMimeType: "application/json" }
  });
  
  const systemInstruction = `You are a senior software architect and product analyst listening to a client meeting. Your job is to extract structured software requirements from the conversation in real-time. You ONLY respond with valid JSON. No markdown, no explanation, just the JSON object.`;

  const prompt = `
${systemInstruction}

Here is the latest transcript from a client meeting:
<transcript>
${transcript}
</transcript>

${
  existingBlueprint
    ? `Here is what we have extracted so far. UPDATE and IMPROVE it with new information:
<existing>
${JSON.stringify(existingBlueprint, null, 2)}
</existing>`
    : "This is the first chunk. Extract everything you can."
}

Return a JSON object with EXACTLY this structure:
{
  "summary": {
    "overview": "2-3 sentence project description",
    "decisions": ["decision 1", "decision 2"],
    "outOfScope": ["item 1", "item 2"],
    "timeline": "if mentioned"
  },
  "requirements": {
    "p0": [{"title": "", "description": ""}],
    "p1": [{"title": "", "description": ""}],
    "p2": [{"title": "", "description": ""}]
  },
  "userFlows": {
    "flows": [
      {
        "name": "Flow name",
        "actor": "who does this",
        "steps": ["step 1", "step 2"]
      }
    ],
    "screens": ["Screen 1", "Screen 2"]
  },
  "techSpec": {
    "frontend": [],
    "backend": [],
    "integrations": [],
    "deploymentPreferences": [],
    "dataEntities": ["Entity 1", "Entity 2"],
    "constraints": []
  },
  "actionItems": [
    {"text": "", "owner": "", "priority": "HIGH|MEDIUM|LOW"}
  ],
  "confidence": {
    "requirements": 0,
    "userFlows": 0,
    "techContext": 0,
    "dataModel": 0,
    "reasoning": "what's still unclear"
  },
  "clarifyingQuestions": ["Question to ask the client?"]
}`;

  try {
    const result = await model.generateContent(prompt);
    let text = result.response.text().trim();
    text = text.replace(/^```json/gi, '').replace(/```$/g, '').trim();
    return JSON.parse(text);
  } catch (error) {
    console.error("Gemini API Error in analyzeTranscriptChunk:", error);
    return getDefaultAnalysis(transcript);
  }
}

export async function generateFullBlueprint(
  fullTranscript: string,
  partialBlueprint: object,
  clientHistoryContext?: string
): Promise<{ blueprint: any; fullPrompt: string }> {
  if (!genAI) {
    console.warn("GEMINI_API_KEY is missing. Returning default master prompt.");
    return {
      blueprint: getDefaultAnalysis(fullTranscript),
      fullPrompt: `# Master AI Coding Prompt (Generated by FlowMeet)\n\nBuild the application according to the meeting notes:\n\n${fullTranscript.slice(0, 1000)}`
    };
  }

  const model = genAI.getGenerativeModel({ 
    model: "gemini-2.5-flash",
    generationConfig: { responseMimeType: "application/json" }
  });

  const prompt = `
You are a senior software architect. You have listened to a client discovery meeting.
Your job is to produce:
1. A complete, structured software blueprint
2. A master prompt that a developer can paste into an AI coding agent (Claude Code, Cursor, etc.) to build the entire application

You ONLY respond with valid JSON. No markdown fences, no explanation.

${clientHistoryContext ? `PREVIOUS MEETINGS CONTEXT FOR THIS CLIENT:\n<history>\n${clientHistoryContext}\n</history>\n` : ""}

Full meeting transcript:
<transcript>
${fullTranscript}
</transcript>

Partial analysis done so far:
<partial>
${JSON.stringify(partialBlueprint, null, 2)}
</partial>

Produce the final JSON with this structure:
{
  "blueprint": {
    "projectName": "",
    "oneLiner": "",
    "summary": { "overview": "", "decisions": [], "outOfScope": [], "timeline": "" },
    "requirements": { "p0": [], "p1": [], "p2": [] },
    "userFlows": { "flows": [], "screens": [] },
    "techSpec": {
      "recommended": {
        "frontend": ["Next.js 15", "TypeScript", "Tailwind CSS", "shadcn/ui"],
        "backend": ["Next.js API Routes", "Prisma", "PostgreSQL"],
        "auth": ["NextAuth.js"],
        "integrations": [],
        "deployment": ["Vercel", "Supabase"]
      },
      "dataModel": [
        { "model": "ModelName", "fields": ["field1: Type", "field2: Type"], "relations": [] }
      ],
      "businessRules": [],
      "constraints": []
    },
    "actionItems": [],
    "openQuestions": [],
    "confidence": { "requirements": 85, "userFlows": 80, "techContext": 90, "dataModel": 85 }
  },
  "fullPrompt": "THE COMPLETE MASTER PROMPT TEXT — write this as if you are writing instructions for an AI developer. Include project overview, all requirements, all screens, full data model, tech stack, business rules, and end with 'Start by building in this order: 1. ... 2. ... 3. ...'"
}`;

  try {
    const result = await model.generateContent(prompt);
    let text = result.response.text().trim();
    text = text.replace(/^```json/gi, '').replace(/```$/g, '').trim();
    return JSON.parse(text);
  } catch (error) {
    console.error("Gemini API Error in generateFullBlueprint:", error);
    return {
      blueprint: getDefaultAnalysis(fullTranscript),
      fullPrompt: `# Master AI Coding Prompt (Generated from Meeting)\n\n## Project Overview\n${fullTranscript.slice(0, 1000)}\n\n## Architecture Recommendation\n- Frontend: Next.js with TypeScript and Tailwind CSS\n- Backend: Next.js API Routes with Prisma ORM\n- Database: PostgreSQL`
    };
  }
}

function getDefaultAnalysis(transcript: string) {
  const preview = transcript.slice(0, 200);
  return {
    summary: {
      overview: preview ? `Meeting discussion covering: ${preview}...` : "Meeting in progress. Waiting for discussion points...",
      decisions: ["Initial requirements identified"],
      outOfScope: ["Unspecified third-party features"],
      timeline: "To be determined"
    },
    requirements: {
      p0: [{ title: "Core Functionality", description: "Implement primary user requirements discussed in call." }],
      p1: [{ title: "User Management & Auth", description: "Role based access and session security." }],
      p2: [{ title: "Export & Reporting", description: "Generate reports and export data." }]
    },
    userFlows: {
      flows: [{ name: "Primary Flow", actor: "User", steps: ["Login", "Access Workspace", "Perform core task"] }],
      screens: ["Dashboard", "Workspace", "Settings"]
    },
    techSpec: {
      frontend: ["Next.js", "TypeScript", "Tailwind CSS"],
      backend: ["Node.js", "Prisma ORM"],
      integrations: [],
      dataEntities: ["User", "Client", "Session", "Project"]
    },
    actionItems: [
      { text: "Review meeting decisions with client", owner: "Team", priority: "HIGH" }
    ],
    confidence: {
      requirements: 75,
      userFlows: 70,
      techContext: 80,
      dataModel: 75,
      reasoning: "Extracted from meeting discussion"
    },
    clarifyingQuestions: []
  };
}
